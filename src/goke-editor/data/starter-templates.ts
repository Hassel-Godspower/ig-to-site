export function starterCategories(): string[] {
  return Array.from(new Set(STARTER_TEMPLATES.map((t) => t.category))).sort();
}

export function startersByCategory(category?: string): StarterTemplate[] {
  if (!category || category === "All") return STARTER_TEMPLATES;
  return STARTER_TEMPLATES.filter((t) => t.category === category);
}

export function findStarter(id: string): StarterTemplate | undefined {
  return STARTER_TEMPLATES.find((t) => t.id === id);
}
